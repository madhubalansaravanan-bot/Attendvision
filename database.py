def get_attendance_history(
    date_filter=None,
    subject_id=None,
    hour=None,
    student_id=None,
    section=None,
):
    query = """
        SELECT ar.id, ar.timestamp, ar.status, ar.confidence,
               s.roll_number, s.name AS student_name,
               sub.subject_name, sub.subject_code,
               sess.date, sess.hour, sess.section
        FROM attendance_records ar
        JOIN students s ON s.id = ar.student_id
        JOIN attendance_sessions sess ON sess.id = ar.session_id
        JOIN subjects sub ON sub.id = sess.subject_id
        WHERE 1=1
    """

    params = []

    if date_filter:
        query += " AND sess.date=%s"
        params.append(date_filter)

    if subject_id:
        query += " AND sub.id=%s"
        params.append(subject_id)

    if hour is not None:
        query += " AND sess.hour=%s"
        params.append(hour)

    if student_id:
        query += " AND s.id=%s"
        params.append(student_id)

    if section:
        query += " AND sess.section=%s"
        params.append(section)

    query += " ORDER BY sess.date DESC, sess.hour DESC"

    with get_connection() as conn:
        return conn.execute(query, params).fetchall()


# ---------------- Dashboard ----------------

def get_dashboard_stats(today: str = None):
    today = today or date_cls.today().isoformat()

    with get_connection() as conn:
        total_students = conn.execute(
            "SELECT COUNT(*) AS n FROM students"
        ).fetchone()["n"]

        todays_classes = conn.execute("""
            SELECT COUNT(*) AS n
            FROM attendance_sessions
            WHERE date=%s
        """, (today,)).fetchone()["n"]

        present_today = conn.execute("""
            SELECT COUNT(DISTINCT ar.student_id) AS n
            FROM attendance_records ar
            JOIN attendance_sessions sess ON sess.id=ar.session_id
            WHERE sess.date=%s AND ar.status='present'
        """, (today,)).fetchone()["n"]

    absent_today = max(total_students - present_today, 0)

    pct = (
        round((present_today / total_students) * 100, 1)
        if total_students else 0.0
    )

    return {
        "todays_classes": todays_classes,
        "total_students": total_students,
        "present_today": present_today,
        "absent_today": absent_today,
        "attendance_percentage": pct,
    }


def get_student_attendance_percentage(student_id):
    with get_connection() as conn:
        total_sessions = conn.execute("""
            SELECT COUNT(*) AS n
            FROM attendance_sessions sess
            JOIN students s
              ON s.section=sess.section OR sess.section IS NULL
            WHERE s.id=%s
        """, (student_id,)).fetchone()["n"]

        present = conn.execute("""
            SELECT COUNT(*) AS n
            FROM attendance_records
            WHERE student_id=%s AND status='present'
        """, (student_id,)).fetchone()["n"]

    if total_sessions == 0:
        return 0.0

    return round((present / total_sessions) * 100, 1)
def get_student_subject_attendance(student_id):
    """Return subject-wise attendance for one student."""

    with get_connection() as conn:
        rows = conn.execute("""
            SELECT
                sub.id AS subject_id,
                sub.subject_code,
                sub.subject_name,
                sub.semester,
                COUNT(sess.id) AS classes_conducted,
                COUNT(ar.id) FILTER (
                    WHERE ar.status = 'present'
                ) AS classes_attended
            FROM students st
            JOIN subjects sub
              ON LOWER(TRIM(COALESCE(sub.department, '')))
                 = LOWER(TRIM(COALESCE(st.department, '')))
             AND LOWER(TRIM(COALESCE(sub.year, '')))
                 = LOWER(TRIM(COALESCE(st.year, '')))
            JOIN attendance_sessions sess
              ON sess.subject_id = sub.id
             AND sess.status = 'closed'
             AND (
                 sess.section IS NULL
                 OR LOWER(TRIM(COALESCE(sess.section, '')))
                    = LOWER(TRIM(COALESCE(st.section, ''))
                    )
             )
            LEFT JOIN attendance_records ar
              ON ar.session_id = sess.id
             AND ar.student_id = st.id
            WHERE st.id = %s
            GROUP BY
                sub.id,
                sub.subject_code,
                sub.subject_name,
                sub.semester
            ORDER BY sub.semester, sub.subject_code
        """, (student_id,)).fetchall()

    summary = []

    for row in rows:
        conducted = int(row["classes_conducted"] or 0)
        attended = int(row["classes_attended"] or 0)
        absent = max(conducted - attended, 0)

        summary.append({
            "subject_code": row["subject_code"],
            "subject_name": row["subject_name"],
            "semester": row["semester"],
            "classes_conducted": conducted,
            "classes_attended": attended,
            "classes_absent": absent,
            "attendance_percentage": (
                round(attended / conducted * 100, 1)
                if conducted else 0.0
            ),
        })

    return summary

